#!/usr/bin/env python3
"""Build three mutually exclusive deployment profiles from reviewed YAML sources."""
from pathlib import Path
import argparse
import copy
import difflib
import yaml

ROOT=Path(__file__).resolve().parents[1]
SCENARIO=ROOT/'scenarios/sk-91'
HEADER='# Generated by tools/build_alert_rules.py; edit catalog/ or scenarios/sk-91/policies/, then rebuild.\n'

def read(path):
    return yaml.safe_load(path.read_text())

def encode(data):
    return HEADER+yaml.safe_dump(data,allow_unicode=True,sort_keys=False,width=110)

def build():
    generic=read(ROOT/'catalog/linux/node_alerts.yml')
    base=read(SCENARIO/'policies/test-base.yml')
    policy=read(SCENARIO/'policies/profile-policy.yml')
    # Test base contains ONLY OOM memory alerts. The recommended policy adds early warning.
    memory=next(g for g in generic['groups'] if g['name']=='node_memory_alerts')
    recommended=copy.deepcopy(base)
    test_memory=next(g for g in recommended['groups'] if g['name']=='node_nonprod_memory_alerts')
    for override in policy['test_memory_recommended']:
        source=next(r for r in memory['rules'] if r['alert']==override['alert'])
        r=copy.deepcopy(source)
        r['labels']['environment_class']='nonprod'
        for k in ['expr','for','keep_firing_for']:
            if k in override:r[k]=override[k]
        r['annotations'].update(override.get('annotations',{}))
        test_memory['rules'].append(r)
    production=copy.deepcopy(generic)
    for g in production['groups']:
        g['name']=g['name'].replace('node_','node_prod_',1)
        for r in g['rules']:
            override=policy['production']['overrides'][r['alert']]
            for k in ['expr','for','keep_firing_for']:
                if k in override:
                    r[k]=override[k]
                elif k!='expr':
                    r.pop(k,None)
            r['labels']['severity']=override['severity']
            r['labels']['environment_class']=policy['production']['environment_class']
            r['annotations'].update(override.get('annotations',{}))
            # Add scope only to selectors already present, and bare recording selectors explicitly.
            r['expr']=r['expr'].replace('job="node_exporter"','job="node_exporter",alert_policy!~"nonprod|stress"')
            import re
            r['expr']=re.sub(r'(node:[a-zA-Z0-9_:]+)(?![a-zA-Z0-9_:]|\{)',r'\1{alert_policy!~"nonprod|stress"}',r['expr'])
    # Preserve mixed-target support: explicit nonprod/stress targets in production use OOM-only policy.
    mixed=copy.deepcopy(base)
    for g in mixed['groups']:
        for r in g['rules']:
            r['expr']=r['expr'].replace('alert_policy=~".*"','alert_policy=~"nonprod|stress"')
            r['labels'].pop('environment_class',None)
    production['groups']=mixed['groups']+production['groups']
    files={}
    for name,node in [('production',production),('test-recommended',recommended),('test-memory-oom-only',base)]:
        files[SCENARIO/name/'node_alerts.yml']=encode(node)
        files[SCENARIO/name/'node_recording.yml']=encode(read(ROOT/'catalog/linux/node_recording.yml'))
        files[SCENARIO/name/'prometheus_self.yml']=encode(read(ROOT/'catalog/platform/prometheus.yml'))
    return files

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    changed=[]
    for path,text in build().items():
        current=path.read_text() if path.exists() else ''
        if current!=text:
            changed.append(str(path.relative_to(ROOT)))
            if args.check:print(''.join(difflib.unified_diff(current.splitlines(True),text.splitlines(True),fromfile=str(path),tofile='expected')))
            else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if args.check and changed:raise SystemExit('Generated profiles are stale: '+', '.join(changed))
    print('Profiles consistent' if args.check else 'Profiles generated')

if __name__=='__main__':main()
